-- Computers' subcategories move to Electronics, keeping Computers' checks as their own.
UPDATE "classified_categories" AS c SET "parent_id" = e."id", "safety_checklist" = CASE WHEN cardinality(c."safety_checklist") = 0 THEN p."safety_checklist" ELSE c."safety_checklist" END, "updated_at" = CURRENT_TIMESTAMP
FROM "classified_categories" e, "classified_categories" p
WHERE e."slug" = 'electronics' AND p."slug" = 'computers' AND c."parent_id" = p."id";
-- Anything pointing at Computers itself points at Electronics, then Computers goes.
UPDATE "classified_listings" SET "category_id" = (SELECT "id" FROM "classified_categories" WHERE "slug" = 'electronics') WHERE "category_id" = (SELECT "id" FROM "classified_categories" WHERE "slug" = 'computers');
UPDATE "resale_rules" SET "category_id" = (SELECT "id" FROM "classified_categories" WHERE "slug" = 'electronics') WHERE "category_id" = (SELECT "id" FROM "classified_categories" WHERE "slug" = 'computers');
UPDATE "classified_feature_suggestions" SET "category_id" = (SELECT "id" FROM "classified_categories" WHERE "slug" = 'electronics') WHERE "category_id" = (SELECT "id" FROM "classified_categories" WHERE "slug" = 'computers');
DELETE FROM "classified_categories" WHERE "slug" = 'computers';

