-- Udozo's brand registry (1 November 2026): the brands sellers pick for the `brand` feature, the categories each sells
-- in, and the brands sellers typed that it lacks.

CREATE TABLE "classified_brands" (
    "id" UUID NOT NULL,
    "slug" TEXT NOT NULL,
    "name" TEXT NOT NULL,
    "name_key" TEXT NOT NULL,
    "aliases" TEXT[] DEFAULT ARRAY[]::TEXT[],
    "match_keys" TEXT[] DEFAULT ARRAY[]::TEXT[],
    "logo_file" TEXT,
    "logo_url" TEXT,
    "color" TEXT,
    "enabled" BOOLEAN NOT NULL DEFAULT true,
    "created_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "classified_brands_pkey" PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX "classified_brands_slug_key" ON "classified_brands"("slug");
CREATE UNIQUE INDEX "classified_brands_name_key_key" ON "classified_brands"("name_key");
ALTER TABLE "classified_brands" ADD CONSTRAINT "classified_brands_name_check" CHECK (char_length("name") BETWEEN 1 AND 60 AND char_length("name_key") >= 1);
ALTER TABLE "classified_brands" ADD CONSTRAINT "classified_brands_color_check" CHECK ("color" IS NULL OR "color" ~ '^#[0-9A-F]{6}$');
ALTER TABLE "classified_brands" ADD CONSTRAINT "classified_brands_logo_url_check" CHECK ("logo_url" IS NULL OR "logo_url" LIKE 'https://%');

CREATE TABLE "classified_brand_categories" (
    "brand_id" UUID NOT NULL,
    "category_id" UUID NOT NULL,
    "position" INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT "classified_brand_categories_pkey" PRIMARY KEY ("brand_id", "category_id")
);

CREATE INDEX "classified_brand_categories_category_id_position_idx" ON "classified_brand_categories"("category_id", "position");
ALTER TABLE "classified_brand_categories" ADD CONSTRAINT "classified_brand_categories_brand_id_fkey" FOREIGN KEY ("brand_id") REFERENCES "classified_brands"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "classified_brand_categories" ADD CONSTRAINT "classified_brand_categories_category_id_fkey" FOREIGN KEY ("category_id") REFERENCES "classified_categories"("id") ON DELETE CASCADE ON UPDATE CASCADE;

CREATE TABLE "classified_brand_suggestions" (
    "id" UUID NOT NULL,
    "customer_id" UUID NOT NULL,
    "name" TEXT NOT NULL,
    "name_key" TEXT NOT NULL,
    "category_id" UUID,
    "status" TEXT NOT NULL DEFAULT 'open',
    "brand_id" UUID,
    "decided_by_id" UUID,
    "decided_at" TIMESTAMP(3),
    "created_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "classified_brand_suggestions_pkey" PRIMARY KEY ("id")
);

CREATE INDEX "classified_brand_suggestions_status_name_key_idx" ON "classified_brand_suggestions"("status", "name_key");
CREATE INDEX "classified_brand_suggestions_customer_id_created_at_idx" ON "classified_brand_suggestions"("customer_id", "created_at");
-- One open suggestion per seller and brand.
CREATE UNIQUE INDEX "classified_brand_suggestions_open_key" ON "classified_brand_suggestions"("customer_id", "name_key") WHERE "status" = 'open';
ALTER TABLE "classified_brand_suggestions" ADD CONSTRAINT "classified_brand_suggestions_customer_id_fkey" FOREIGN KEY ("customer_id") REFERENCES "customers"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "classified_brand_suggestions" ADD CONSTRAINT "classified_brand_suggestions_category_id_fkey" FOREIGN KEY ("category_id") REFERENCES "classified_categories"("id") ON DELETE SET NULL ON UPDATE CASCADE;
ALTER TABLE "classified_brand_suggestions" ADD CONSTRAINT "classified_brand_suggestions_brand_id_fkey" FOREIGN KEY ("brand_id") REFERENCES "classified_brands"("id") ON DELETE SET NULL ON UPDATE CASCADE;
ALTER TABLE "classified_brand_suggestions" ADD CONSTRAINT "classified_brand_suggestions_status_check" CHECK ("status" IN ('open', 'added', 'dismissed'));
ALTER TABLE "classified_brand_suggestions" ADD CONSTRAINT "classified_brand_suggestions_decided_check" CHECK (("status" = 'open') = ("decided_at" IS NULL));

