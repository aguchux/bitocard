-- Checks the database enforces whatever the code does.
ALTER TABLE "classified_features" ADD CONSTRAINT "classified_features_key_check" CHECK ("key" ~ '^[a-z][a-z0-9_]*$');
ALTER TABLE "classified_features" ADD CONSTRAINT "classified_features_data_type_check" CHECK ("data_type" IN ('text', 'number', 'choice', 'boolean'));
ALTER TABLE "classified_features" ADD CONSTRAINT "classified_features_choices_check" CHECK (("data_type" = 'choice') = (cardinality("choices") > 0));
ALTER TABLE "classified_features" ADD CONSTRAINT "classified_features_limits_check" CHECK (("min" IS NULL AND "max" IS NULL AND "unit" IS NULL) OR "data_type" = 'number');
ALTER TABLE "classified_features" ADD CONSTRAINT "classified_features_range_check" CHECK ("min" IS NULL OR "max" IS NULL OR "min" <= "max");
ALTER TABLE "classified_features" ADD CONSTRAINT "classified_features_boolean_default_check" CHECK ("data_type" <> 'boolean' OR "default_value" IS NULL OR "default_value" IN ('true', 'false'));
ALTER TABLE "classified_categories" ADD CONSTRAINT "classified_categories_slug_check" CHECK ("slug" ~ '^[a-z0-9]+(-[a-z0-9]+)*$');
ALTER TABLE "classified_categories" ADD CONSTRAINT "classified_categories_not_own_parent_check" CHECK ("parent_id" IS NULL OR "parent_id" <> "id");
ALTER TABLE "classified_areas" ADD CONSTRAINT "classified_areas_kind_check" CHECK (("kind" = 'state' AND "parent_id" IS NULL) OR ("kind" = 'area' AND "parent_id" IS NOT NULL));
ALTER TABLE "classified_areas" ADD CONSTRAINT "classified_areas_slug_check" CHECK ("slug" ~ '^[a-z0-9]+(-[a-z0-9]+)*$');
ALTER TABLE "classified_areas" ADD CONSTRAINT "classified_areas_position_check" CHECK ("latitude" BETWEEN -90 AND 90 AND "longitude" BETWEEN -180 AND 180);
ALTER TABLE "classified_safe_pay_settings" ADD CONSTRAINT "classified_safe_pay_settings_fees_check" CHECK (
  ("buyer_fee_bps" IS NULL OR "buyer_fee_bps" BETWEEN 0 AND 10000) AND ("seller_fee_bps" IS NULL OR "seller_fee_bps" BETWEEN 0 AND 10000)
  AND ("buyer_fee_cap_minor" IS NULL OR "buyer_fee_cap_minor" >= 0) AND ("seller_fee_cap_minor" IS NULL OR "seller_fee_cap_minor" >= 0)
  AND ("new_seller_order_limit_minor" IS NULL OR "new_seller_order_limit_minor" > 0));
ALTER TABLE "classified_safe_pay_settings" ADD CONSTRAINT "classified_safe_pay_settings_times_check" CHECK ("accept_hours" BETWEEN 1 AND 168 AND "pay_hours" BETWEEN 1 AND 168 AND "handover_days" BETWEEN 1 AND 60 AND "confirm_days" BETWEEN 1 AND 30);

