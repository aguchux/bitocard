/** What the AI agent step can offer: BitoCard's models (Premium) and the models on the reseller's own keys. */
export type AiChoices = { premium: boolean; bitocard: Partial<Record<BotProvider, string[]>>; own: Partial<Record<BotProvider, string[]>> };

export type AssistantContext = {
  base: BotsBase;
  admin: boolean;
  stores: Array<{ id: string; name: string }>;
  ai: AiChoices;
  realm: MediaRealm;
  avatarPurpose: MediaPurpose;
  /** Whose assistant and AI it is, in the copy (default BitoCard; Afrippa's admin says Afrippa). */
  brand?: string;
  /** Whether the knowledge can be updated section by section from the store (BitoCard's stores); else generated again. */
  refresh?: boolean;
};

const brandOf = (context: AssistantContext) => context.brand ?? productName();

/** The role, AI agent and profile fields: the wizard's first steps, and the profile card later. */
export function AssistantProfileForm({
  context,
  initial,
  submitLabel,
  busy,
  error,
  onSubmit,
  showStore = false,
}: {
  context: AssistantContext;
  initial?: Partial<SupportBot>;
  submitLabel: string;
  busy?: boolean;
  error?: string | null;
  onSubmit: (input: BotInput) => void;
  showStore?: boolean;
}) {
  const id = useId();
  const [roles, setRoles] = useState<Array<'chat' | 'tickets'>>(initial?.roles?.filter((role): role is 'chat' | 'tickets' => role === 'chat' || role === 'tickets') ?? ['chat', 'tickets']);
  const [funding, setFunding] = useState<'bitocard' | 'own'>(initial?.funding ?? (context.ai.premium ? 'bitocard' : 'own'));
  const models = funding === 'bitocard' ? context.ai.bitocard : context.ai.own;
  const providers = (Object.keys(models) as BotProvider[]).filter(item => (models[item] ?? []).length || funding === 'own');
  const [provider, setProvider] = useState<BotProvider>(initial?.provider ?? providers[0] ?? 'anthropic');
  const [model, setModel] = useState(initial?.model ?? models[provider]?.[0] ?? '');
  const [name, setName] = useState(initial?.name ?? '');
  const [avatar, setAvatar] = useState(initial?.avatar_url ?? '');
  const [greeting, setGreeting] = useState(initial?.greeting ?? '');
  const [tone, setTone] = useState<'friendly' | 'formal' | 'brief'>(initial?.tone ?? 'friendly');
  const [instructions, setInstructions] = useState(initial?.instructions ?? '');
  const [ticketMode, setTicketMode] = useState<'auto' | 'draft'>(initial?.ticket_reply_mode ?? 'draft');
  const [store, setStore] = useState(initial?.store_id ?? context.stores[0]?.id ?? '');
  const options = models[provider] ?? [];
  const valid = roles.length > 0 && name.trim().length >= 2 && model.trim().length >= 2;

  const toggleRole = (role: 'chat' | 'tickets') => setRoles(current => (current.includes(role) ? current.filter(item => item !== role) : [...current, role]));
  const pickFunding = (next: 'bitocard' | 'own') => {
    setFunding(next);
    const list = next === 'bitocard' ? context.ai.bitocard : context.ai.own;
    const first = (Object.keys(list) as BotProvider[]).find(item => (list[item] ?? []).length) ?? provider;
    setProvider(first);
    setModel(list[first]?.[0] ?? '');
  };
  const submit = (event: FormEvent) => {
    event.preventDefault();
    if (!valid) return;
    onSubmit({
      roles,
      funding,
      provider,
      model: model.trim(),
      name: name.trim(),
      avatar_url: avatar || null,
      greeting: greeting.trim() || null,
      tone,
      instructions: instructions.trim() || null,
      ticket_reply_mode: ticketMode,
      ...(showStore && store ? { store_id: store } : {}),
    });
  };

  return (
    <form onSubmit={submit} className="space-y-6" noValidate>
      {error ? <Notice tone="red">{error}</Notice> : null}
      <section className="space-y-3">
        <h3 className="font-bold text-ink">1. Role</h3>
        <div className="flex flex-wrap gap-3">
          {(['chat', 'tickets'] as const).map(role => (
            <label key={role} className={cn('flex min-h-11 cursor-pointer items-center gap-2 rounded-xl border px-4 text-sm font-semibold', roles.includes(role) ? 'border-brand-400 bg-brand-50 text-brand-700' : 'border-line text-ink')}>
              <input type="checkbox" className="size-4" checked={roles.includes(role)} onChange={() => toggleRole(role)} />
              {role === 'chat' ? 'Answers chats' : 'Replies to tickets'}
            </label>
          ))}
        </div>
        {roles.includes('tickets') ? (
          <Field label="Ticket replies" htmlFor={`${id}-mode`} hint="Start with drafts: your team sends each one, until you trust the assistant to reply by itself.">
            <Select id={`${id}-mode`} value={ticketMode} onChange={event => setTicketMode(event.target.value as 'auto' | 'draft')}>
              <option value="draft">Suggest a draft for staff to send</option>
              <option value="auto">Reply automatically</option>
            </Select>
          </Field>
        ) : null}
      </section>
      <section className="space-y-3">
        <h3 className="font-bold text-ink">2. AI agent</h3>
        {!context.admin ? (
          <div className="grid gap-3 sm:grid-cols-2">
            <button type="button" onClick={() => pickFunding('bitocard')} disabled={!context.ai.premium} className={cn('rounded-2xl border p-4 text-left disabled:opacity-60', funding === 'bitocard' ? 'border-brand-400 bg-brand-50' : 'border-line')}>
              <p className="font-semibold text-ink">{`${productName()}’s AI`}</p>
              <p className="text-sm text-muted">{context.ai.premium ? 'Included with Premium, within a monthly allowance.' : 'Needs the Premium plan.'}</p>
            </button>
            <button type="button" onClick={() => pickFunding('own')} className={cn('rounded-2xl border p-4 text-left', funding === 'own' ? 'border-brand-400 bg-brand-50' : 'border-line')}>
              <p className="font-semibold text-ink">Your own AI key</p>
              <p className="text-sm text-muted">{Object.keys(context.ai.own).length ? 'You pay your provider for what it uses.' : 'Add a key in Support > AI keys first.'}</p>
            </button>
          </div>
        ) : null}
        <div className="grid gap-3 sm:grid-cols-2">
          <Field label="Provider" htmlFor={`${id}-provider`}>
            <Select
              id={`${id}-provider`}
              value={provider}
              onChange={event => {
                const next = event.target.value as BotProvider;
                setProvider(next);
                setModel(models[next]?.[0] ?? '');
              }}
            >
              {(['anthropic', 'openai', 'deepseek'] as const).map(item => (
                <option key={item} value={item} disabled={!(models[item] ?? []).length && funding === 'bitocard'}>
                  {providerLabels[item]}
                </option>
              ))}
            </Select>
          </Field>
          <Field label="Model" htmlFor={`${id}-model`}>
            {options.length ? (
              <Select id={`${id}-model`} value={model} onChange={event => setModel(event.target.value)}>
                {options.map(item => (
                  <option key={item} value={item}>
                    {item}
                  </option>
                ))}
              </Select>
            ) : (
              <Input id={`${id}-model`} value={model} onChange={event => setModel(event.target.value)} placeholder="Model name" />
            )}
          </Field>
        </div>
      </section>
      <section className="space-y-3">
        <h3 className="font-bold text-ink">3. Profile</h3>
        <div className="grid gap-4 sm:grid-cols-[auto_minmax(0,1fr)]">
          <ImageField label="Face or avatar" value={avatar} onChange={setAvatar} realm={context.realm} purpose={context.avatarPurpose} shape="square" hint="A square image, at least 128 px." />
          <div className="space-y-3">
            <Field label="Name" htmlFor={`${id}-name`} hint="Customers see it, with “AI assistant” beside it.">
              <Input id={`${id}-name`} maxLength={40} value={name} onChange={event => setName(event.target.value)} />
            </Field>
            <Field label="Greeting" htmlFor={`${id}-greeting`}>
              <Input id={`${id}-greeting`} maxLength={300} value={greeting} onChange={event => setGreeting(event.target.value)} placeholder="Hi! How can I help today?" />
            </Field>
            <Field label="Tone" htmlFor={`${id}-tone`}>
              <Select id={`${id}-tone`} value={tone} onChange={event => setTone(event.target.value as typeof tone)}>
                {(['friendly', 'formal', 'brief'] as const).map(item => (
                  <option key={item} value={item}>
                    {toneLabels[item]}
                  </option>
                ))}
              </Select>
            </Field>
          </div>
        </div>
        <Field label="Extra guidance (optional)" htmlFor={`${id}-instructions`} hint={`House rules for your assistant, for example opening hours or what to say about delivery times. It can never override ${brandOf(context)}’s safety rules.`}>
          <Textarea id={`${id}-instructions`} rows={3} maxLength={2000} value={instructions} onChange={event => setInstructions(event.target.value)} />
        </Field>
        {showStore && context.stores.length ? (
          <Field label="Store" htmlFor={`${id}-store`} hint="One assistant per store.">
            <Select id={`${id}-store`} value={store} onChange={event => setStore(event.target.value)}>
              {context.stores.map(item => (
                <option key={item.id} value={item.id}>
                  {item.name}
                </option>
              ))}
            </Select>
          </Field>
        ) : null}
      </section>
      <div className="flex justify-end">
        <Button type="submit" loading={busy} disabled={!valid}>
          {submitLabel}
        </Button>
      </div>
    </form>
  );
}

function download(filename: string, content: string) {
  const url = URL.createObjectURL(new Blob([content], { type: filename.endsWith('.csv') ? 'text/csv' : 'text/markdown' }));
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  link.click();
  URL.revokeObjectURL(url);
}

const stateLabels: Record<SectionChange['state'], string> = { unchanged: 'No change', changed: 'Store changed', added: 'New section', edited: 'You edited this' };

/** Update knowledge base: what changed in the store, section by section, and which BitoCard sections to apply. */
function RefreshDialog({
  base,
  botId,
  open,
  onClose,
  sections,
  loading,
  loadError,
}: {
  base: BotsBase;
  botId: string;
  open: boolean;
  onClose: () => void;
  sections: SectionChange[] | undefined;
  loading: boolean;
  loadError: unknown;
}) {
  const [apply, applyState] = useApplyBotRefreshMutation();
  // Until the owner changes it: every section the store changed, never one they edited.
  const [picked, setPicked] = useState<ManagedSectionKey[] | null>(null);
  const chosen = picked ?? (sections ?? []).filter(item => item.state === 'changed' || item.state === 'added').map(item => item.key);
  const close = () => {
    applyState.reset();
    onClose();
  };
  const changed = sections?.filter(item => item.state !== 'unchanged') ?? [];
  return (
    <Dialog
      open={open}
      onClose={close}
      title="Update knowledge base"
      description={`${productName()} rewrites its own sections from your store as it is now. Your own sections are never touched; a section you edited is replaced only if you tick it.`}
      footer={
        <>
          <Button variant="ghost" onClick={close}>
            Cancel
          </Button>
          <Button
            icon={<RefreshCw className="size-4" aria-hidden />}
            loading={applyState.isLoading}
            disabled={!chosen.length}
            onClick={async () => {
              if (await apply({ base, id: botId, apply: chosen }).unwrap().catch(() => null)) close();
            }}
          >
            {chosen.length ? `Apply ${chosen.length} ${chosen.length === 1 ? 'section' : 'sections'}` : 'Apply'}
          </Button>
        </>
      }
    >
      <div className="space-y-3">
        {loading ? <p className="text-sm text-muted">Comparing your store with the knowledge base…</p> : null}
        {loadError ? <Notice tone="red">{errorMessage(loadError)}</Notice> : null}
        {applyState.error ? <Notice tone="red">{errorMessage(applyState.error)}</Notice> : null}
        {sections && !changed.length ? <Notice tone="green">Your knowledge base matches your store: nothing to update.</Notice> : null}
        {changed.map(section => (
          <div key={section.key} className={cn('rounded-xl border p-3', section.state === 'edited' ? 'border-amber-200 bg-amber-50' : 'border-line')}>
            <label className="flex items-start gap-3">
              <input
                type="checkbox"
                className="mt-1 size-4"
                checked={chosen.includes(section.key)}
                onChange={() => setPicked(chosen.includes(section.key) ? chosen.filter(item => item !== section.key) : [...chosen, section.key])}
              />
              <span className="min-w-0 flex-1">
                <span className="flex flex-wrap items-center gap-2 font-semibold text-ink">
                  {section.title}
                  <Badge tone={section.state === 'edited' ? 'amber' : 'blue'}>{stateLabels[section.state]}</Badge>
                </span>
                <span className="block text-sm text-muted">
                  {section.added || section.removed ? `${section.added} added, ${section.removed} removed` : section.state === 'edited' ? `Ticking it replaces your edit with ${productName()}’s version.` : 'Wording updated.'}
                </span>
              </span>
            </label>
            <details className="mt-2 text-sm">
              <summary className="cursor-pointer text-brand-600">Compare</summary>
              <div className="mt-2 grid gap-2 md:grid-cols-2">
                <pre className="max-h-48 overflow-auto rounded-lg bg-white p-2 text-xs whitespace-pre-wrap ring-1 ring-line">{section.current ?? '(not in your document)'}</pre>
                <pre className="max-h-48 overflow-auto rounded-lg bg-emerald-50 p-2 text-xs whitespace-pre-wrap ring-1 ring-emerald-100">{section.fresh}</pre>
              </div>
            </details>
          </div>
        ))}
      </div>
    </Dialog>
  );
}

/** The knowledge step: template, upload, Generate from BitoCard, edit, Update knowledge base, versions. */
export function KnowledgePanel({ context, bot }: { context: AssistantContext; bot: SupportBot }) {
  const id = useId();
  const query = useBotKnowledgeQuery({ base: context.base, id: bot.id });
  const [save, saveState] = useSaveBotKnowledgeMutation();
  const [generate, generateState] = useGenerateBotKnowledgeMutation();
  const [restore] = useRestoreBotKnowledgeMutation();
  const [update] = useUpdateSupportBotMutation();
  const [template] = useLazyKnowledgeTemplateQuery();
  const [preview, previewState] = usePreviewBotRefreshMutation();
  const [draft, setDraft] = useState<{ content: string; source: 'edited' | 'generated' } | null>(null);
  const [refreshing, setRefreshing] = useState(false);
  const knowledge = query.data;
  const error = saveState.error ?? generateState.error;

  const getTemplate = async (format: 'md' | 'csv') => {
    const result = await template({ admin: context.admin, format }).unwrap().catch(() => null);
    if (result) download(result.filename, result.content);
  };
  const upload = async (event: ChangeEvent<HTMLInputElement>) => {
    const file = event.target.files?.[0];
    event.target.value = '';
    if (!file) return;
    const content = await file.text();
    await save({ base: context.base, id: bot.id, content, format: file.name.toLowerCase().endsWith('.csv') ? 'csv' : 'md', source: 'upload' }).unwrap().catch(() => null);
  };
  const generated = async () => {
    const result = await generate({ base: context.base, id: bot.id }).unwrap().catch(() => null);
    if (result) setDraft({ content: result.content, source: 'generated' });
  };

  return (
    <Card className="space-y-4 p-5">
      <CardHeader title="Knowledge" description="What your assistant knows about your business. Markdown works best; a CSV of FAQs (question, answer, category) is turned into Markdown." className="px-0 pt-0 pb-0" />
      {error ? <Notice tone="red">{errorMessage(error)}</Notice> : null}
      {bot.knowledge_stale_at ? (
        <Notice tone="amber" title="Your store has changed since the knowledge base was updated">
          Products, payments or policies changed. Update the knowledge base to bring {productName()}’s sections up to date.
        </Notice>
      ) : null}
      <div className="flex flex-wrap gap-2">
        <Button variant="secondary" size="sm" icon={<Download className="size-4" aria-hidden />} onClick={() => void getTemplate('md')}>
          Template (.md)
        </Button>
        <Button variant="secondary" size="sm" icon={<Download className="size-4" aria-hidden />} onClick={() => void getTemplate('csv')}>
          FAQ template (.csv)
        </Button>
        <label htmlFor={`${id}-file`} className="inline-flex min-h-9 cursor-pointer items-center gap-2 rounded-xl border border-line bg-white px-3 text-sm font-semibold text-ink hover:bg-canvas">
          <FileUp className="size-4" aria-hidden /> Upload
        </label>
        <input id={`${id}-file`} type="file" accept=".md,.markdown,.txt,.csv,text/markdown,text/plain,text/csv" className="sr-only" onChange={event => void upload(event)} />
        {bot.store_id ? (
          <Button variant="secondary" size="sm" icon={<Sparkles className="size-4" aria-hidden />} loading={generateState.isLoading} onClick={() => void generated()}>
            {`Generate from ${brandOf(context)}`}
          </Button>
        ) : null}
        {knowledge?.current && bot.store_id && context.refresh !== false ? (
          <Button
            variant="secondary"
            size="sm"
            icon={<RefreshCw className="size-4" aria-hidden />}
            onClick={() => {
              setRefreshing(true);
              void preview({ base: context.base, id: bot.id });
            }}
          >
            Update knowledge base
          </Button>
        ) : null}
        {knowledge?.current ? (
          <Button variant="ghost" size="sm" icon={<Wand2 className="size-4" aria-hidden />} onClick={() => setDraft({ content: knowledge.current!.content, source: 'edited' })}>
            Edit
          </Button>
        ) : null}
      </div>
      {draft ? (
        <div className="space-y-2">
          <Field label={draft.source === 'generated' ? `Generated by ${brandOf(context)}: read it, fill in your own sections, then apply` : 'Edit your knowledge'} htmlFor={`${id}-draft`} hint={`${draft.content.length.toLocaleString('en-GB')} of ${(knowledge?.max_chars ?? 60000).toLocaleString('en-GB')} characters. Keep the <!-- bitocard: --> markers so updates can find BitoCard’s sections.`}>
            <Textarea id={`${id}-draft`} rows={18} className="font-mono text-xs" value={draft.content} onChange={event => setDraft({ ...draft, content: event.target.value })} />
          </Field>
          <div className="flex justify-end gap-2">
            <Button variant="ghost" onClick={() => setDraft(null)}>
              Cancel
            </Button>
            <Button
              loading={saveState.isLoading}
              onClick={async () => {
                if (await save({ base: context.base, id: bot.id, content: draft.content, source: draft.source }).unwrap().catch(() => null)) setDraft(null);
              }}
            >
              Apply
            </Button>
          </div>
        </div>
      ) : knowledge?.current ? (
        <details className="rounded-xl border border-line">
          <summary className="cursor-pointer p-3 text-sm font-semibold text-ink">{`Version ${knowledge.current.version} · ${sourceLabels[knowledge.current.source] ?? knowledge.current.source} · ${knowledge.current.chars.toLocaleString('en-GB')} characters`}</summary>
          <pre className="max-h-96 overflow-auto border-t border-line p-3 text-xs whitespace-pre-wrap">{knowledge.current.content}</pre>
        </details>
      ) : (
        <Notice tone="blue">{`No knowledge yet. Generate it from ${brandOf(context)}${context.refresh === false ? '' : ' (assign a store first)'}, or download a template, fill it in and upload it.`}</Notice>
      )}
      {bot.store_id && context.refresh !== false ? (
        <label className="flex items-center gap-3 text-sm text-ink">
          <Toggle checked={bot.auto_refresh} onChange={value => void update({ base: context.base, id: bot.id, body: { auto_refresh: value } })} label="Automatic updates" />
          Automatic updates: apply {productName()}’s sections by itself when the store changes (never your own or ones you edited)
        </label>
      ) : null}
      {knowledge && knowledge.versions.length > 1 ? (
        <details className="text-sm">
          <summary className="cursor-pointer text-brand-600">Versions</summary>
          <ul className="mt-2 space-y-1">
            {knowledge.versions.map(version => (
              <li key={version.version} className="flex flex-wrap items-center justify-between gap-2">
                <span>{`Version ${version.version} · ${sourceLabels[version.source] ?? version.source} · ${formatRelative(version.created_at)}`}</span>
                {version.current ? (
                  <Badge tone="green">In use</Badge>
                ) : (
                  <Button variant="ghost" size="sm" onClick={() => void restore({ base: context.base, id: bot.id, version: version.version })}>
                    Restore
                  </Button>
                )}
              </li>
            ))}
          </ul>
        </details>
      ) : null}
      <RefreshDialog
        key={`r-${refreshing}-${previewState.requestId ?? ''}`}
        base={context.base}
        botId={bot.id}
        open={refreshing}
        onClose={() => setRefreshing(false)}
        sections={previewState.data?.sections}
        loading={previewState.isLoading}
        loadError={previewState.error}
      />
    </Card>
  );
}

/** The playground: a conversation with the assistant as it is now. Nothing is kept. */
export function AssistantTest({ context, bot }: { context: AssistantContext; bot: SupportBot }) {
  const [test, state] = useTestSupportBotMutation();
  const [messages, setMessages] = useState<Array<{ id: string; author: string; author_name: string | null; body: string; created_at: string }>>([]);
  return (
    <Card className="space-y-3 p-5">
      <CardHeader title="Try it" description="Ask what your customers would. This uses your assistant’s AI (and counts as usage, not towards the allowance)." className="px-0 pt-0 pb-0" />
      <ChatPanel
        messages={messages}
        side="reseller"
        error={state.error ? errorMessage(state.error) : null}
        placeholder="Ask your assistant something"
        onSend={async body => {
          const asked = [...messages, { id: `u${messages.length}`, author: 'reseller', author_name: 'You', body, created_at: new Date().toISOString() }];
          setMessages(asked);
          const history = asked.map(item => ({ role: item.author === 'bot' ? ('assistant' as const) : ('user' as const), content: item.body }));
          const result = await test({ base: context.base, id: bot.id, messages: history }).unwrap().catch(() => null);
          if (!result) return false;
          setMessages([...asked, { id: `b${asked.length}`, author: 'bot', author_name: bot.name, body: result.reply || '(no answer)', created_at: new Date().toISOString() }]);
          return true;
        }}
      />
    </Card>
  );
}

function Step({ done, title, children }: { done: boolean; title: string; children?: ReactNode }) {
  return (
    <li className="flex gap-3">
      {done ? <CheckCircle2 className="size-5 shrink-0 text-emerald-600" aria-hidden /> : <Circle className="size-5 shrink-0 text-muted" aria-hidden />}
      <div className="min-w-0 text-sm">
        <p className="font-semibold text-ink">{title}</p>
        {children ? <div className="text-muted">{children}</div> : null}
      </div>
    </li>
  );
}

/** An assistant's page: the steps left, then profile, store, knowledge and the playground, and activating it. */
export function AssistantDetail({ context, bot, extraActions }: { context: AssistantContext; bot: SupportBot; extraActions?: ReactNode }) {
  const id = useId();
  const [update, updateState] = useUpdateSupportBotMutation();
  const [activate, activateState] = useActivateSupportBotMutation();
  const [pause, pauseState] = usePauseSupportBotMutation();
  const [editing, setEditing] = useState(false);
  const error = updateState.error ?? activateState.error ?? pauseState.error;
  const storeScoped = bot.scope === 'store';

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-3">
          {bot.avatar_url ? (
            // eslint-disable-next-line @next/next/no-img-element -- an uploaded file on the storage CDN
            <img src={bot.avatar_url} alt="" className="size-14 rounded-full object-cover ring-1 ring-line" />
          ) : <span className="grid size-14 place-items-center rounded-full bg-violet-50 text-violet-600"><Bot className="size-7" aria-hidden /></span>}
          <div>
            <h1 className="text-2xl font-extrabold tracking-tight text-ink">{bot.name}</h1>
            <p className="text-sm text-muted">{`${bot.roles.map(role => roleLabels[role]).join(' and ')} · ${providerLabels[bot.provider]} ${bot.model} · ${bot.funding === 'own' ? 'your key' : `${brandOf(context)}’s AI`}`}</p>
          </div>
          <StatusBadge status={bot.status === 'active' ? 'active' : bot.status === 'suspended' ? 'failed' : 'pending'} label={botStatusLabels[bot.status]} />
        </div>
        <div className="flex flex-wrap gap-2">
          {extraActions}
          {bot.status === 'active' ? (
            <Button variant="secondary" loading={pauseState.isLoading} onClick={() => void pause({ base: context.base, id: bot.id })}>
              Pause
            </Button>
          ) : bot.status !== 'suspended' ? (
            <Button loading={activateState.isLoading} onClick={() => void activate({ base: context.base, id: bot.id })}>
              Activate
            </Button>
          ) : null}
        </div>
      </div>
      {error ? <Notice tone="red">{errorMessage(error)}</Notice> : null}
      {bot.status === 'suspended' ? <Notice tone="red" title={`Suspended by ${productName()}`}>{bot.suspended_reason ?? `Contact ${productName()} support.`}</Notice> : null}
      <div className="grid gap-4 lg:grid-cols-[minmax(0,2fr)_minmax(0,1fr)]">
        <div className="space-y-4">
          <KnowledgePanel context={context} bot={bot} />
          <AssistantTest context={context} bot={bot} />
        </div>
        <div className="space-y-4">
          <Card className="p-5">
            <CardHeader title="Steps" className="px-0 pt-0 pb-3" />
            <ol className="space-y-3">
              <Step done title="Role and AI agent">{bot.roles.map(role => roleLabels[role]).join(' and ')}</Step>
              <Step done title="Profile">{bot.name}</Step>
              <Step done={Boolean(bot.knowledge)} title="Knowledge">{bot.knowledge ? `Version ${bot.knowledge.version}` : 'Upload or generate it'}</Step>
              {storeScoped ? <Step done={Boolean(bot.store_id)} title="Assigned to a store">{bot.store_name ?? 'Choose a store below'}</Step> : null}
              <Step done={bot.status === 'active'} title="Tested and active">{bot.status === 'active' ? 'Answering now' : 'Try it, then activate'}</Step>
            </ol>
          </Card>
          {storeScoped ? (
            <Card className="space-y-3 p-5">
              <CardHeader title="Store" description="One assistant per store." className="px-0 pt-0 pb-0" />
              <Field label="Assigned to" htmlFor={`${id}-store`}>
                <Select id={`${id}-store`} value={bot.store_id ?? ''} onChange={event => void update({ base: context.base, id: bot.id, body: { store_id: event.target.value || null } })}>
                  <option value="">No store</option>
                  {context.stores.map(store => (
                    <option key={store.id} value={store.id}>
                      {store.name}
                    </option>
                  ))}
                </Select>
              </Field>
            </Card>
          ) : null}
          <Card className="space-y-3 p-5">
            <CardHeader title="Role, AI and profile" className="px-0 pt-0 pb-0" actions={<Button variant="ghost" size="sm" onClick={() => setEditing(value => !value)}>{editing ? 'Close' : 'Edit'}</Button>} />
            {editing ? (
              <AssistantProfileForm
                context={context}
                initial={bot}
                submitLabel="Save"
                busy={updateState.isLoading}
                onSubmit={async input => {
                  if (await update({ base: context.base, id: bot.id, body: input }).unwrap().catch(() => null)) setEditing(false);
                }}
              />
            ) : (
              <dl className="space-y-1 text-sm">
                <div className="flex justify-between gap-2"><dt className="text-muted">Greeting</dt><dd className="text-right">{bot.greeting ?? '—'}</dd></div>
                <div className="flex justify-between gap-2"><dt className="text-muted">Tone</dt><dd>{toneLabels[bot.tone]}</dd></div>
                {bot.roles.includes('tickets') ? <div className="flex justify-between gap-2"><dt className="text-muted">Ticket replies</dt><dd>{bot.ticket_reply_mode === 'auto' ? 'Automatic' : 'Drafts for staff'}</dd></div> : null}
                <div className="flex justify-between gap-2"><dt className="text-muted">Updated</dt><dd>{formatDateTime(bot.updated_at)}</dd></div>
              </dl>
            )}
          </Card>
        </div>
      </div>
    </div>
  );
}
